import { swiftClient } from "@cluenori/openapi-swift"
import { CluenoriApi, CluenoriIngestApi } from "@cluenori/worker"
import { Effect, Schema } from "effect"
import { OpenApi } from "effect/http-api"

import { refuse } from "./refuse.ts"

// Each named Schema is a component under its own name: `Phone`, not the `PhoneEncoded` Effect gives
// the wire form of a class, so the document and other languages' clients use the code's names.
const named = {
  referencePolicy: ({ identifier }: { readonly identifier: string | undefined }) => identifier?.replace(/Encoded$/, ""),
}

const document = OpenApi.fromApi(CluenoriApi, named)

const JsonText = Schema.fromJsonString(Schema.Unknown, { space: 2 })

/** Where the committed OpenAPI document lives; the Kotlin SDK will build from it. */
const openApiPath = "apps/worker/openapi.json"

const openApiDocument = Schema.encodeEffect(JsonText)(document).pipe(
  Effect.map((text) => `${text}\n`),
  // Plain JSON data always encodes.
  Effect.orDie,
)

// The iOS app's client of the public API, written from the same document.
const swiftClientPath = "apps/ios/CluenoriApp/Sources/CluenoriClient/CluenoriAPI.swift"

const swiftClientText = swiftClient(document).pipe(
  Effect.map(
    (swift) =>
      `// Generated by \`bun run generate\` from the API's definition. Don't edit.\n// swift-format-ignore-file\n\n${swift}`,
  ),
  Effect.catchTag("UnsupportedOpenApi", (unsupported) =>
    refuse(
      `The API has something the Swift client can't be written for, at ${unsupported.path} of ${openApiPath}: ${unsupported.reason}.`,
    ),
  ),
)

// The ingest API apps' SDKs call, and the Swift SDK's client of it.
const ingestDocument = OpenApi.fromApi(CluenoriIngestApi, named)
const ingestOpenApiPath = "sdks/swift/openapi.json"
const ingestOpenApiDocument = Schema.encodeEffect(JsonText)(ingestDocument).pipe(
  Effect.map((text) => `${text}\n`),
  Effect.orDie,
)
const ingestSwiftPath = "sdks/swift/Sources/CluenoriIngest/CluenoriIngestAPI.swift"
const ingestSwiftText = swiftClient(ingestDocument).pipe(
  Effect.map(
    (swift) =>
      `// Generated by \`bun run generate\` from the ingest API's definition. Don't edit.\n// swift-format-ignore-file\n\n${swift}`,
  ),
  Effect.catchTag("UnsupportedOpenApi", (unsupported) =>
    refuse(
      `The ingest API has something the Swift client can't be written for, at ${unsupported.path} of ${ingestOpenApiPath}: ${unsupported.reason}.`,
    ),
  ),
)

/**
 * Every file generated from code, and what it holds: the public API's OpenAPI document and the iOS
 * app's Swift client of it; the ingest API's document and the Swift SDK's client of it. `bun run
 * generate` writes them; `bun run check` fails when one differs.
 */
export const generatedFiles = [
  { path: openApiPath, text: openApiDocument },
  { path: swiftClientPath, text: swiftClientText },
  { path: ingestOpenApiPath, text: ingestOpenApiDocument },
  { path: ingestSwiftPath, text: ingestSwiftText },
]
