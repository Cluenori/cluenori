import { Console, Effect, FileSystem, Schema } from "effect"
import { Command } from "effect/cli"
import { ChildProcess, ChildProcessSpawner } from "effect/process"

import { refuse } from "./api-client.ts"

/** Where the table of Apple's model names is written. */
export const appleModelsPath = "product/engines/phones/src/apple-models.ts"

// What `xcrun simctl list devicetypes --json` answers, of what the table needs.
const DeviceTypes = Schema.Struct({
  devicetypes: Schema.Array(
    Schema.Struct({ name: Schema.String, modelIdentifier: Schema.String, productFamily: Schema.String }),
  ),
})

// Machine text, so sorted by code point, the same on every machine.
const byCodePoint = (left: string, right: string) => {
  if (left === right) {
    return 0
  }
  return left < right ? -1 : 1
}

/**
 * `bun run generate:apple-models`: rewrites the table of what people call each iPhone and iPad
 * model, from Xcode's own list of simulated devices. Needs a Mac with Xcode; run it when a new
 * Xcode knows new devices.
 */
export const appleModels = Command.make("apple-models", {}, () =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
    const listed = yield* spawner
      .string(ChildProcess.make("xcrun", ["simctl", "list", "devicetypes", "--json"]))
      .pipe(Effect.catch(() => refuse("This needs a Mac with Xcode: `xcrun simctl` lists the devices it knows.")))
    const { devicetypes } = yield* Schema.decodeEffect(Schema.fromJsonString(DeviceTypes))(listed).pipe(Effect.orDie)
    const names = new Map<string, string>()
    for (const device of devicetypes.toSorted((left, right) => byCodePoint(left.name, right.name))) {
      if (
        (device.productFamily === "iPhone" || device.productFamily === "iPad") &&
        !names.has(device.modelIdentifier)
      ) {
        names.set(device.modelIdentifier, device.name)
      }
    }
    const rows = [...names].toSorted(([left], [right]) => byCodePoint(left, right))
    const table = [
      "// Generated by `bun run generate:apple-models` from Xcode's list of simulated devices",
      "// (`xcrun simctl list devicetypes`). Don't edit: run it again when a new Xcode knows new devices.",
      "",
      "/** What people call each iPhone and iPad model, by Apple's identifier: `iPhone19,3` is an iPhone 18 Pro Max. */",
      "export const appleModels: ReadonlyMap<string, string> = new Map([",
      ...rows.map(([identifier, name]) => `  [${JSON.stringify(identifier)}, ${JSON.stringify(name)}],`),
      "])",
      "",
    ].join("\n")
    yield* fs.writeFileString(appleModelsPath, table).pipe(Effect.orDie)
    yield* Console.log(`Wrote ${appleModelsPath}: ${rows.length} models.`)
  }),
).pipe(
  Command.withDescription("Rewrite the table of Apple's model names from Xcode's simulators. Needs a Mac with Xcode."),
)
